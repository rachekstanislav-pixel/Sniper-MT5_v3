"""Reproduce the one-file EA without modifying the canonical BASE source."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'Sniper_Manager_v3_6_5_BASE_ATR_RESTORED_VISUAL.mq5'
OUTPUT = ROOT / 'Sniper_Manager_v3_6_5_NEWS_VIRTUAL.mq5'


def build():
    base = BASE.read_text(encoding='utf-8')
    hooks = [
        ('   ServiceVisuals(true);\n   return INIT_SUCCEEDED;', '   ServiceVisuals(true);\n   News_InitOptional();\n   return INIT_SUCCEEDED;'),
        ('void OnDeinit(const int reason) {', 'void OnDeinit(const int reason) {\n   News_OnDeinit(reason);\n   ObjectDelete(0,G_VisualPrefix+"NEWS_STATUS");'),
        ('void OnTimer() {', 'void OnTimer() {\n   // DiagnosticMode preserves the original promise: no network requests.\n   if(!DiagnosticMode) News_OnTimer();\n   News_RenderStatus();'),
        ('void OnTick() {', 'void OnTick() {\n   News_OnTick();'),
    ]
    for before, after in hooks:
        if base.count(before) != 1:
            raise RuntimeError('Baseline hook changed: ' + before)
        base = base.replace(before, after, 1)
    engine = (ROOT / 'news/mt5/SniperNews.mqh').read_text(encoding='utf-8')
    render = (ROOT / 'news/render_status.mqpart').read_text(encoding='utf-8')
    base = base.replace('int OnInit() {', engine + '\n' + render + '\nint OnInit() {', 1)
    return '// Full BASE 3.65 plus optional virtual news. Generated by news/build_integrated.py.\n' + base


if __name__ == '__main__':
    OUTPUT.write_text(build(), encoding='utf-8')
