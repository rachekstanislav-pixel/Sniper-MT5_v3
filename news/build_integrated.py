from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'Sniper_Manager_v3_6_5_BASE_ATR_RESTORED_VISUAL.mq5'
OUTPUT = ROOT / 'Sniper_Manager_v3_6_7_NEWS_TESTER.mq5'


def build():
    base = BASE.read_text(encoding='utf-8')
    isolation = '   if(!News_TesterValidate(EnableAutoTrade,DiagnosticMode,MagicNumber)) return INIT_PARAMETERS_INCORRECT;\n'
    hooks = [
        ('int OnInit() {\n', 'int OnInit() {\n'+isolation),
        ('   ServiceVisuals(true);\n   return INIT_SUCCEEDED;', '   ServiceVisuals(true);\n   News_InitOptional();\n   if(News_TesterOrders && !News_ready) return INIT_FAILED;\n   return INIT_SUCCEEDED;'),
        ('void OnDeinit(const int reason) {', 'void OnDeinit(const int reason) {\n   News_OnDeinit(reason);\n   ObjectDelete(0,G_VisualPrefix+"NEWS_STATUS");'),
        ('void OnTimer() {', 'void OnTimer() {\n   // DiagnosticMode preserves the original promise: no network requests.\n   if(!DiagnosticMode) News_OnTimer();\n   News_RenderStatus();'),
        ('void OnTick() {', 'void OnTick() {\n   News_OnTick();'),
    ]
    for before, after in hooks:
        if base.count(before) != 1:
            raise RuntimeError('Baseline hook changed: ' + before)
        base = base.replace(before, after, 1)
    base = base.replace('request.expiration=TimeCurrent()+(long)BaseMaxWaitBars*PeriodSeconds(_Period);', 'request.expiration=(datetime)((long)TimeCurrent()+(long)BaseMaxWaitBars*PeriodSeconds(_Period));')
    base = base.replace('#property version "3.65"', '#property version "3.67"')
    engine = (ROOT / 'news/mt5/SniperNews.mqh').read_text(encoding='utf-8')
    render = (ROOT / 'news/render_status.mqpart').read_text(encoding='utf-8')
    settings = (ROOT / 'news/mt5/SniperNewsTesterSettings.mqh').read_text(encoding='utf-8')
    adapter = (ROOT / 'news/mt5/SniperNewsTester.mqh').read_text(encoding='utf-8')
    base = base.replace('int OnInit() {', settings + '\n' + engine + '\n' + adapter + '\n' + render + '\nint OnInit() {', 1)
    return '// Sniper Manager 3.67 / News 0.5.0 / tester orders opt-in; trading baseline 3.65 preserved. Generated by news/build_integrated.py.\n' + base


if __name__ == '__main__':
    OUTPUT.write_text(build(), encoding='utf-8')
